  /* Locale tag → table. Regional variants resolve through BASE below. */
  const LOCALES = {
    en,
    'zh-CN': zhHans,
    'zh-TW': zhHant,
    ja,
    ko,
    de,
    fr,
    es,
    pt,
    ru,
  };

  /* Which locale a bare/unknown regional tag falls back to. */
  const BASE = {
    zh: 'zh-CN',
    'zh-hans': 'zh-CN',
    'zh-sg': 'zh-CN',
    'zh-my': 'zh-CN',
    'zh-hant': 'zh-TW',
    'zh-hk': 'zh-TW',
    'zh-mo': 'zh-TW',
    'pt-br': 'pt',
    'pt-pt': 'pt',
  };

  /** Best match for a list of BCP-47 tags (most preferred first). */
  function resolve(preferred) {
    const tags = (Array.isArray(preferred) ? preferred : [preferred]).filter(Boolean);
    for (const raw of tags) {
      const tag = String(raw).toLowerCase();
      if (BASE[tag]) return BASE[tag];
      const exact = Object.keys(LOCALES).find((k) => k.toLowerCase() === tag);
      if (exact) return exact;
      const primary = tag.split('-')[0];
      if (BASE[primary]) return BASE[primary];
      const byPrimary = Object.keys(LOCALES).find((k) => k.toLowerCase().split('-')[0] === primary);
      if (byPrimary) return byPrimary;
    }
    return 'en';
  }

  return {
    locales: LOCALES,
    fallback: en,
    resolve,
    /** `[{ tag, name }]` for the language picker, English first. */
    list() {
      return Object.entries(LOCALES).map(([tag, table]) => ({ tag, name: table._name }));
    },
  };
